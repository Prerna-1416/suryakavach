from __future__ import annotations

from suryakavach.evaluation.schemas import EvaluationRun


def generate_markdown_report(eval_run: EvaluationRun) -> str:
    """Renders a structured, GitHub-flavored Markdown report from an EvaluationRun."""
    dm = eval_run.detection_metrics
    lt = eval_run.lead_time_stats
    cis = eval_run.confidence_intervals
    cal = eval_run.calibration_curve

    lines = [
        "# SURYAKAVACH Evaluation Report",
        "",
        f"**Run ID:** `{eval_run.id}`  ",
        f"**Timestamp:** `{eval_run.created_at}`  ",
        f"**Source Cohort:** `{eval_run.source_cohort}`  ",
        f"**Split ID:** `{eval_run.split_id}`  ",
        f"**Model Version:** `{eval_run.model_version}`  ",
        f"**Dataset Hash:** `{eval_run.dataset_hash[:16]}`  ",
        f"**Config Hash:** `{eval_run.config_hash[:16]}`  ",
        f"**Code Revision:** `{eval_run.code_revision[:16]}`  ",
        "",
    ]

    if eval_run.source_cohort == "synthetic":
        lines.extend([
            "> [!WARNING]",
            "> **Synthetic Demo Cohort:** This evaluation was executed on a synthetic/simulated dataset.",
            "> Results serve for regression testing only and do NOT constitute an operational solar flare forecast claim.",
            "",
        ])
    elif eval_run.source_cohort == "observed_uncalibrated":
        lines.extend([
            "> [!NOTE]",
            "> **Observed Uncalibrated Data:** Evaluated on uncalibrated instrument counts.",
            "> Requires validated flux calibration before operational R-scale mapping.",
            "",
        ])
    else:
        lines.extend([
            "> [!IMPORTANT]",
            "> **Observed Calibrated Cohort:** Operational-candidate evaluation on calibrated observations.",
            "",
        ])

    # Detection Skill Section
    tss_ci = cis.get("tss")
    hss_ci = cis.get("hss")
    far_ci = cis.get("far")

    tss_str = f"{dm.tss:.3f}" + (f" (95% CI: [{tss_ci.ci_lower:.3f}, {tss_ci.ci_upper:.3f}])" if tss_ci else "")
    hss_str = f"{dm.hss:.3f}" + (f" (95% CI: [{hss_ci.ci_lower:.3f}, {hss_ci.ci_upper:.3f}])" if hss_ci else "")
    far_str = f"{dm.far:.3f}" + (f" (95% CI: [{far_ci.ci_lower:.3f}, {far_ci.ci_upper:.3f}])" if far_ci else "")

    lines.extend([
        "## Detection Performance (All Classes, ±15 min match window)",
        "",
        f"- **TSS (True Skill Statistic):** {tss_str}",
        f"- **HSS (Heidke Skill Score):** {hss_str}",
        f"- **FAR (False Alarm Ratio):** {far_str}",
        f"- **Precision:** {dm.precision:.3f} | **Recall:** {dm.recall:.3f} | **F1 Score:** {dm.f1:.3f}",
        f"- **Counts:** TP={dm.tp}, FP={dm.fp}, FN={dm.fn}, TN={dm.tn} (Total samples: {eval_run.sample_count})",
        "",
    ])

    # Lead Time Section
    lead_ci = cis.get("lead_time_mean")
    lead_mean_str = f"{lt.mean:.1f} min" + (f" (95% CI: [{lead_ci.ci_lower:.1f}, {lead_ci.ci_upper:.1f}] min)" if lead_ci else "")

    lines.extend([
        "## Detected Flare Lead Time Distribution",
        "",
        f"- **Mean Lead Time (Onset to Peak):** {lead_mean_str}",
        f"- **Median:** {lt.median:.1f} min | **IQR (25th - 75th %):** {lt.p25:.1f} - {lt.p75:.1f} min",
        f"- **Range:** {lt.min_val:.1f} min (min) to {lt.max_val:.1f} min (max) | **Std Dev:** {lt.std:.1f} min",
        "",
    ])

    # Forecast Brier Scores
    lines.extend([
        "## Per-Horizon Forecast Brier Scores",
        "",
        "| Horizon (min) | Brier Score |",
        "|---|---:|",
    ])
    for h, score in sorted(eval_run.horizon_brier_scores.items()):
        lines.append(f"| t+{h} min | {score:.4f} |")
    lines.append("")

    # Reliability & Calibration
    lines.extend([
        "## Reliability & Calibration Curve",
        "",
        f"- **Overall Brier Score:** {cal.brier_score:.4f}",
        f"- **Brier Skill Score (vs Climatology):** {cal.brier_skill_score:.4f}",
        "",
        "| Bin Center | Predicted Prob | Observed Frequency | Count |",
        "|---|---:|---:|---:|",
    ])
    for pt in cal.points:
        lines.append(f"| {pt.bin_center:.2f} | {pt.prob_pred:.4f} | {pt.prob_true:.4f} | {pt.count} |")
    lines.append("")

    # Failure Slices
    if eval_run.failure_slices:
        lines.extend([
            "## Failure Slice Analysis",
            "",
            "| Slice | Sample Count | TP | FP | FN | TN | TSS | HSS | FAR |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ])
        for name, fs in eval_run.failure_slices.items():
            lines.append(
                f"| {name} | {fs.sample_count} | {fs.tp} | {fs.fp} | {fs.fn} | {fs.tn} | {fs.tss:.3f} | {fs.hss:.3f} | {fs.far:.3f} |"
            )
        lines.append("")

    lines.extend([
        "---",
        "*Report auto-generated by SURYAKAVACH evaluation framework.*",
    ])

    return "\n".join(lines) + "\n"
